/**
 * Una ruta de combi SIT Arequipa.
 *
 * Los puntos (lat, lon) son waypoints aproximados para dibujar el trazado
 * en el mapa. Se pueden reemplazar por el trazado real (GeoJSON) cuando
 * se disponga de él.
 */
data class CombiRoute(
    val id: String,            // "C2", "C2-A", ...
    val name: String,          // "Línea C2" / "C2 · Variante A"
    val operator: String,      // empresa concesionaria
    val color: Color,
    /** Waypoints (lat, lon) del recorrido, del punto de partida al retorno. */
    val waypoints: List<Pair<Double, Double>>,
    /** true si es una sub-ruta (variante) de una línea principal. */
    val isSub: Boolean = false,
    /** id de la línea principal a la que pertenece (null si es principal). */
    val parent: String? = null,
    /** id de la ruta en SmartBus (para cargar su trazado real). */
    val routeId: String? = null,
    val returnRouteId: String? = null,
    val returnName: String? = null,
)

